function spot(anchors, index) {
  const items = anchors.filter((anchor) => anchor.kind !== 'floor')
  const list = items.length ? items : anchors
  return list[index % list.length]
}

function callNode(id, text, choices, givesClueId = '') {
  return { id, text, givesClueId, choices }
}

function choice(label, goto) {
  return { label, goto }
}

function base({ title, logline, briefing, people, culpritId, motive, summary, motives, clues, calls }) {
  return {
    title,
    logline,
    briefing,
    truth: { culpritId, motive, summary },
    people,
    motives,
    clues,
    calls,
  }
}

